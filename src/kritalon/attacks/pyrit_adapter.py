"""Optional PyRIT adapter behind Kritalon's `AdaptiveStrategy` interface.

`pyrit` is intentionally an optional extra (`uv sync --extra pyrit`) so the default
installation stays lightweight. All PyRIT imports happen lazily inside this module; the
rest of Kritalon never depends on PyRIT's types.

Safety invariants preserved across the bridge:
- PyRIT's attacker talks to the target ONLY through `_ChannelPromptTarget`, which routes
  every turn through Kritalon's `ProbeChannel` (enforcing `Meter`, `require_contained_tools`,
  fresh canaries, and turn-by-turn contamination checking).
- `_EvidenceScorer` scores strictly from Kritalon's deterministic evidence (`verified`),
  never using an LLM judge and never exposing any canary value to PyRIT.
"""

from __future__ import annotations

import importlib
from collections.abc import Sequence
from dataclasses import dataclass, field
from typing import Any

from kritalon.attacks.strategy import Objective, ProbeChannel, ProbeFeedback, SearchResult
from kritalon.core.models import Attack, Attempt, Turn


def _load_pyrit() -> Any:
    """Import PyRIT lazily, raising an actionable error if the optional extra is not installed."""
    try:
        return importlib.import_module("pyrit")
    except ImportError as exc:
        raise RuntimeError(
            "PyRIT is not installed. Install the optional extra with `uv sync --extra pyrit` "
            "or use the built-in `--strategy adaptive` strategy instead."
        ) from exc


class _ChannelBridge:
    """Routes single-turn calls from an external multi-turn attacker into one ProbeChannel episode."""

    def __init__(self, objective: Objective, channel: ProbeChannel, max_turns: int) -> None:
        self.objective = objective
        self.channel = channel
        self.max_turns = max_turns
        self.sent_turns: list[str] = []
        self.last_feedback: ProbeFeedback | None = None
        self.verified = False


@dataclass
class PyRITAdaptiveStrategy:
    """Run a PyRIT multi-turn attack (e.g. Crescendo, PAIR, RedTeaming) behind `AdaptiveStrategy`.

    Parameters
    ----------
    adversarial_chat
        A PyRIT `PromptChatTarget` used by PyRIT to generate adversarial turns.
    attack_kind
        Which PyRIT v1 attack executor to use: `"crescendo"`, `"pair"`, or `"red_teaming"`.
    max_turns
        Maximum target turns per episode.
    pyrit_module
        Optional module injection for unit tests; defaults to lazily importing `pyrit`.
    """

    adversarial_chat: Any
    attack_kind: str = "crescendo"
    max_turns: int = 4
    name: str = "adaptive-pyrit"
    technique: str = "adaptive pyrit"
    _pyrit_module: Any = field(default=None, repr=False)

    def __post_init__(self) -> None:
        if self.attack_kind not in ("crescendo", "pair", "red_teaming"):
            raise ValueError(f"unsupported PyRIT attack_kind {self.attack_kind!r}")
        if self.max_turns < 1:
            raise ValueError("max_turns must be at least 1")

    def _resolve_attack_class(self, pyrit_mod: Any) -> Any:
        mapping = {
            "crescendo": ("pyrit.executor.attack.multi_turn.crescendo", "CrescendoAttack"),
            "pair": ("pyrit.executor.attack.multi_turn.pair", "PAIRAttack"),
            "red_teaming": ("pyrit.executor.attack.multi_turn.red_teaming", "RedTeamingAttack"),
        }
        mod_path, cls_name = mapping[self.attack_kind]
        if hasattr(pyrit_mod, cls_name):
            return getattr(pyrit_mod, cls_name)
        sub = importlib.import_module(mod_path)
        return getattr(sub, cls_name)

    async def search(self, objective: Objective, channel: ProbeChannel) -> SearchResult:
        pyrit_mod = self._pyrit_module if self._pyrit_module is not None else _load_pyrit()
        if channel.stopped or channel.remaining_messages <= 0:
            return SearchResult(objective.id, (), 0)

        attack_cls = self._resolve_attack_class(pyrit_mod)
        turn_budget = min(self.max_turns, channel.remaining_messages)
        attack_id = f"pyrit-{self.attack_kind}:{objective.id}"
        title = f"PyRIT {self.attack_kind} adaptive search"
        calls = [0]

        attack_kind = self.attack_kind
        if objective.kind == "injection":
            # PyRIT's multi-turn chat executors drive conversational turns; for planted text,
            # each turn generated by PyRIT is planted into the injection point and the target's
            # reply to the ordinary user is fed back as the observation.
            episodes: list[tuple[Attack | None, Attempt]] = []
            scored: list[bool] = []

            class _InjectionTarget:
                async def send_prompt_async(self, *, message: Any) -> list[Any]:
                    text = _extract_text(message)
                    if not text.strip() or channel.stopped or channel.remaining_messages <= 0:
                        return []
                    calls[0] += 1
                    ep_id = f"{attack_id}:e{len(episodes) + 1}"
                    attempt, frozen = await channel.try_payload(
                        text,
                        attack_id=ep_id,
                        technique=f"pyrit ({attack_kind})",
                        title=f"{title} (try {len(episodes) + 1})",
                    )
                    episodes.append((frozen, attempt))
                    scored.append(attempt.outcome == "verified")
                    reply = next((t.text for t in reversed(attempt.transcript) if t.role == "target"), "")
                    return [_wrap_reply(pyrit_mod, reply)]

            scorer = _DeterministicScorer(lambda: bool(scored and scored[-1]))
            executor = attack_cls(
                objective_target=_InjectionTarget(),
                attack_adversarial_config=self.adversarial_chat,
                attack_scoring_config=scorer,
                max_turns=turn_budget,
            )
            await channel.within_deadline(executor.execute_async(objective=objective.hint))
            return SearchResult(objective.id, tuple(episodes), calls[0])

        # Conversational (disclosure / action): run PyRIT inside a single ProbeChannel episode
        # via a paired asyncio queue so Kritalon owns reset, canaries, Meter, and freezing.
        import asyncio

        outgoing: asyncio.Queue[str | None] = asyncio.Queue()
        incoming: asyncio.Queue[ProbeFeedback | None] = asyncio.Queue()
        last_verified = [False]

        class _ConversationTarget:
            async def send_prompt_async(self, *, message: Any) -> list[Any]:
                text = _extract_text(message)
                if not text.strip():
                    return [_wrap_reply(pyrit_mod, "")]
                calls[0] += 1
                await outgoing.put(text)
                feedback = await incoming.get()
                if feedback is None:
                    return []
                last_verified[0] = feedback.verified
                return [_wrap_reply(pyrit_mod, feedback.reply_text)]

        scorer = _DeterministicScorer(lambda: last_verified[0])
        executor = attack_cls(
            objective_target=_ConversationTarget(),
            attack_adversarial_config=self.adversarial_chat,
            attack_scoring_config=scorer,
            max_turns=turn_budget,
        )

        async def _drive_pyrit() -> None:
            try:
                await channel.within_deadline(executor.execute_async(objective=objective.hint))
            finally:
                await outgoing.put(None)

        driver = asyncio.create_task(_drive_pyrit())

        async def next_turn(transcript: Sequence[Turn], feedback: ProbeFeedback | None) -> str | None:
            if feedback is not None:
                await incoming.put(feedback)
                if feedback.verified or feedback.error is not None:
                    return None
            return await outgoing.get()

        try:
            attempt, frozen = await channel.run_conversation(
                next_turn,
                attack_id=attack_id,
                technique=f"pyrit ({self.attack_kind})",
                title=title,
                max_turns=turn_budget,
            )
        finally:
            await incoming.put(None)
            if not driver.done():
                driver.cancel()
            try:
                await driver
            except BaseException:
                pass

        return SearchResult(objective.id, ((frozen, attempt),), calls[0])


class _DeterministicScorer:
    """PyRIT-compatible scorer backed exclusively by Kritalon's deterministic evidence."""

    def __init__(self, check: Any) -> None:
        self._check = check

    async def score_async(self, *_args: Any, **_kwargs: Any) -> list[dict[str, Any]]:
        return [{"score_value": bool(self._check()), "score_type": "true_false"}]


def _extract_text(message: Any) -> str:
    if isinstance(message, str):
        return message
    if hasattr(message, "get_value"):
        return str(message.get_value())
    if hasattr(message, "converted_value"):
        return str(message.converted_value)
    if hasattr(message, "request_pieces") and message.request_pieces:
        return _extract_text(message.request_pieces[0])
    return str(message)


def _wrap_reply(pyrit_mod: Any, text: str) -> Any:
    maker = getattr(pyrit_mod, "make_response", None)
    if callable(maker):
        return maker(text)
    return text
